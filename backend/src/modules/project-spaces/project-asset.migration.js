const requiredQcReportColumns = [
  ["online_document_id", "BIGINT NULL"],
  ["document_sync_status", "VARCHAR(32) NULL"],
  ["document_synced_at", "DATETIME NULL"],
  ["document_sync_error", "TEXT NULL"],
];

async function ensureProjectAssetColumns(pool) {
  for (const [columnName, definition] of requiredQcReportColumns) {
    const [rows] = await pool.query(
      `SELECT COUNT(*) AS total
       FROM information_schema.columns
       WHERE table_schema = DATABASE() AND table_name = 'qc_report' AND column_name = ?`,
      [columnName],
    );
    if (Number(rows[0]?.total || 0) === 0) {
      await pool.query(`ALTER TABLE qc_report ADD COLUMN \`${columnName}\` ${definition}`);
    }
  }
}

module.exports = { createTableStatements, postMigrations: [ensureProjectAssetColumns] };
